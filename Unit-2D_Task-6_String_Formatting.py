name = "Akshaya"
age = 18
marks = 95.5

# 1. Using format()
print("Using format(): My name is {} and my age is {}".format(name, age))

# 2. Using f-string
print(f"Using f-string: My name is {name} and my marks are {marks}")

# 3. Using % operator
print("Using % operator: My name is %s and my age is %d" % (name, age))